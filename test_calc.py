from calc import calculate_bmr

def test_bmr_male():
    # Проверяем мужчину: вес 80, рост 180, возраст 30
    # Ожидаемый результат: (10*80) + (6.25*180) - (5*30) + 5 = 800 + 1125 - 150 + 5 = 1780
    result = calculate_bmr('м', 80, 180, 30)
    assert result == 1780

def test_bmr_female():
    # Проверяем женщину: вес 60, рост 165, возраст 25
    # Ожидаемый результат: (10*60) + (6.25*165) - (5*25) - 161 = 600 + 1031.25 - 125 - 161 = 1345.25
    result = calculate_bmr('ж', 60, 165, 25)
    assert result == 1345.25